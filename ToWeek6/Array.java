package ToWeek6;



public class Array {
    public static void main(String[] a)
    {
        int[] reverb = {1,2,3,4,5};
        // Using Enhanced For Loop
        for (int i = 0; i < reverb.length; i++) 
        {
            reverb[i] = reverb[i];
            System.out.println(reverb[i]);
        }
        
}
        
       
}
